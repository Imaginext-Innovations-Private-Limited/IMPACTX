def care_text(group: str, lang: str, crop_key: str = "") -> dict:
    lang = lang if lang in CARE_TEXTS else "en"
    base = dict(CARE_TEXTS[lang].get(group) or CARE_TEXTS["en"][group])
    ck = (crop_key or "").strip().lower()
    if ck:
        key = (ck, group)
        if key not in _CROP_SPECIFIC and key in _CROP_GROUP_FALLBACK_ALIAS:
            key = _CROP_GROUP_FALLBACK_ALIAS[key]
        crop_entry = _CROP_SPECIFIC.get(key)
        if crop_entry:
            vals = crop_entry.get(lang)
            if vals:
                base.update(dict(zip(_FIELDS, vals)))
                base["_is_crop_specific"] = True
    return base


def crop_name(crop_key: str, lang: str) -> str:
    if not crop_key:
        return ""
    row = CROP_NAMES.get(crop_key)
    if not row:
        return crop_key.replace("_", " ").title()
    return row.get(lang) or row["en"]


def message(key: str, lang: str) -> str:
    table = MESSAGES[key]
    return table.get(lang) or table["en"]


def severity_text(level: str, lang: str) -> str:
    table = SEVERITY_TEXTS.get(lang) or SEVERITY_TEXTS["en"]
    return table[level]
