const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    return localStorage.getItem('farm_advisor_lang') || 'kn'
  })

  const setLang = (newLang) => {
    if (LANGUAGES.some((l) => l.code === newLang)) {
      setLangState(newLang)
      try {
        localStorage.setItem('farm_advisor_lang', newLang)
      } catch (e) {}
    }
  }

  const t = (key, fallback = '') => {
    const entry = TRANSLATIONS[key]
    if (!entry) return fallback || key
    return entry[lang] || entry['en'] || fallback || key
  }

  const getCommodityName = (name) => {
    if (!name) return ''
    const entry = COMMODITY_NAMES[name]
    if (!entry) return name
    return entry[lang] || entry['en'] || name
  }

  return (
    <I18nContext.Provider
      value={{
        lang,
        setLang,
        t,
        getCommodityName,
        languages: LANGUAGES,
        currentLanguage: LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0],
      }}
    >
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    // Graceful fallback if used outside provider
    return {
      lang: 'kn',
      setLang: () => {},
      t: (k, fb = '') => TRANSLATIONS[k]?.['kn'] || fb || k,
      getCommodityName: (n) => COMMODITY_NAMES[n]?.['kn'] || n,
      languages: LANGUAGES,
      currentLanguage: LANGUAGES[0],
    }
  }
  return ctx
}

export default I18nContext
