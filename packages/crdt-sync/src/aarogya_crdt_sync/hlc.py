"""Deterministic Hybrid Logical Clock (HLC) for offline-first mesh nodes.

Implements Kulkarni et al.'s Hybrid Logical Clock with strict total ordering on
``(wall_ms, logical, node_id)``. Every autonomous node (Tier-0 Watch, Tier-1
Phone, Tier-2 Hub) can advance its clock offline indefinitely and merge causal
order upon opportunistic peer sync without requiring NTP or cloud coordination.
"""

from __future__ import annotations

import threading
import time
from collections.abc import Callable

from aarogya_contracts import HlcTimestamp


class ClockDriftError(ValueError):
    """Raised when a remote HLC exceeds the configured physical clock drift bound."""


def default_wall_ms() -> int:
    """Return current Unix epoch time in milliseconds."""
    return time.time_ns() // 1_000_000


def compare_hlc(a: HlcTimestamp, b: HlcTimestamp) -> int:
    """Compare two HLC timestamps under total order ``(wall_ms, logical, node_id)``.

    Returns:
        ``-1`` if ``a < b``, ``1`` if ``a > b``, or ``0`` if ``a == b``.
    """
    a_key = a.as_tuple()
    b_key = b.as_tuple()
    if a_key < b_key:
        return -1
    if a_key > b_key:
        return 1
    return 0


def hlc_sort_key(hlc: HlcTimestamp) -> str:
    """Return the canonical lexicographically sortable key for an HLC timestamp."""
    return hlc.to_sort_key()


def parse_hlc_sort_key(sort_key: str) -> HlcTimestamp:
    """Parse a canonical ``wall_ms:logical:node_id`` HLC sort key."""
    parts = sort_key.split(":", maxsplit=2)
    if len(parts) != 3:
        raise ValueError(f"Invalid HLC sort key format: {sort_key!r}")
    wall_raw, logical_raw, node_id = parts
    try:
        wall_ms = int(wall_raw)
        logical = int(logical_raw)
    except ValueError as exc:
        raise ValueError(f"Invalid numeric components in HLC sort key: {sort_key!r}") from exc
    return HlcTimestamp(wall_ms=wall_ms, logical=logical, node_id=node_id)


class HlcClock:
    """Thread-safe Hybrid Logical Clock bound to a single mesh node."""

    def __init__(
        self,
        node_id: str,
        *,
        time_fn: Callable[[], int] | None = None,
        initial_hlc: HlcTimestamp | None = None,
        max_drift_ms: int | None = None,
    ) -> None:
        if not node_id or len(node_id) > 128:
            raise ValueError("node_id must be between 1 and 128 characters")
        if max_drift_ms is not None and max_drift_ms < 0:
            raise ValueError("max_drift_ms must be non-negative")

        self._node_id = node_id
        self._time_fn: Callable[[], int] = time_fn or default_wall_ms
        self._max_drift_ms = max_drift_ms
        self._wall_ms = initial_hlc.wall_ms if initial_hlc is not None else 0
        self._logical = initial_hlc.logical if initial_hlc is not None else 0
        self._lock = threading.Lock()

    @property
    def node_id(self) -> str:
        """Identifier of the mesh node owning this clock."""
        return self._node_id

    @property
    def current(self) -> HlcTimestamp:
        """Latest HLC timestamp observed or generated by this node."""
        with self._lock:
            return HlcTimestamp(
                wall_ms=self._wall_ms,
                logical=self._logical,
                node_id=self._node_id,
            )

    def _physical_ms(self, now_ms: int | None) -> int:
        pt = self._time_fn() if now_ms is None else now_ms
        if pt < 0:
            raise ValueError("Physical timestamp must be non-negative")
        return pt

    def tick(self, now_ms: int | None = None) -> HlcTimestamp:
        """Advance clock for a local event and return the new strictly monotonic HLC."""
        with self._lock:
            pt = self._physical_ms(now_ms)
            if pt > self._wall_ms:
                self._wall_ms = pt
                self._logical = 0
            else:
                self._logical += 1
            return HlcTimestamp(
                wall_ms=self._wall_ms,
                logical=self._logical,
                node_id=self._node_id,
            )

    def receive(self, remote_hlc: HlcTimestamp, now_ms: int | None = None) -> HlcTimestamp:
        """Merge a remote HLC timestamp on message/event receipt.

        Guarantees the returned timestamp is strictly greater than both the
        previous local timestamp and ``remote_hlc`` while staying bounded to
        physical time when physical time advances.
        """
        with self._lock:
            pt = self._physical_ms(now_ms)
            if self._max_drift_ms is not None and (remote_hlc.wall_ms - pt) > self._max_drift_ms:
                raise ClockDriftError(
                    f"Remote HLC wall_ms={remote_hlc.wall_ms} exceeds physical time={pt} "
                    f"by more than max_drift_ms={self._max_drift_ms}"
                )

            l_old = self._wall_ms
            l_remote = remote_hlc.wall_ms
            l_new = max(l_old, l_remote, pt)

            if l_new == l_old and l_new == l_remote:
                self._logical = max(self._logical, remote_hlc.logical) + 1
            elif l_new == l_old:
                self._logical += 1
            elif l_new == l_remote:
                self._logical = remote_hlc.logical + 1
            else:
                self._logical = 0

            self._wall_ms = l_new
            return HlcTimestamp(
                wall_ms=self._wall_ms,
                logical=self._logical,
                node_id=self._node_id,
            )
