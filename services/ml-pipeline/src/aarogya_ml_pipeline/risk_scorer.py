"""LightGBM + TreeSHAP Tabular Risk Scorer for Aarogya Mesh Tier-2 PHC Hub.

Implements ``LightGbmRiskScorer`` conforming to the ``RiskScorer`` protocol.
Features are aligned with ``aarogya_clinical_engine.TriageInput``.

Clinical Safety Invariant:
    Risk scores generated by ML are strictly advisory and NEVER override
    or downgrade deterministic danger signs or triage severity in
    ``aarogya_clinical_engine``.
"""

from __future__ import annotations

import math
import os
from pathlib import Path
from typing import Any, Literal

try:
    import numpy as np
except ImportError:
    np = None  # type: ignore[assignment]

try:
    import lightgbm as lgb
except ImportError:
    lgb = None

from aarogya_ml_pipeline.gbdt_treeshap import DEFAULT_ARTIFACT_PATH, PortableGbdtModel
from aarogya_ml_pipeline.interfaces import (
    RiskScorer,
    RiskScoreResult,
    StubRiskScorer,
)

# Canonical ordered clinical feature names aligned with aarogya_clinical_engine.TriageInput
RISK_FEATURE_NAMES: list[str] = [
    "age_months",
    "fever_days",
    "temperature_c",
    "respiratory_rate_bpm",
    "spo2_pct",
    "systolic_bp",
    "diastolic_bp",
    "hemoglobin_g_dl",
    "muac_cm",
    "is_pregnant",
    "gestational_weeks",
    "has_danger_sign",
    "symptom_count",
]

# Standard clinical defaults for missing features (NaN for LightGBM native tree routing)
DEFAULT_FEATURE_VALUES: dict[str, float] = {
    "age_months": float("nan"),
    "fever_days": 0.0,
    "temperature_c": float("nan"),
    "respiratory_rate_bpm": float("nan"),
    "spo2_pct": float("nan"),
    "systolic_bp": float("nan"),
    "diastolic_bp": float("nan"),
    "hemoglobin_g_dl": float("nan"),
    "muac_cm": float("nan"),
    "is_pregnant": 0.0,
    "gestational_weeks": float("nan"),
    "has_danger_sign": 0.0,
    "symptom_count": 0.0,
}


def _default_model_path() -> Path:
    """Resolve default LightGBM model path from env var or package relative path."""
    env_path = os.environ.get("AAROGYA_RISK_MODEL_PATH")
    if env_path:
        return Path(env_path)
    return Path(__file__).resolve().parent.parent.parent / "models" / "risk_lgbm.txt"


def extract_risk_features(triage_input: Any) -> dict[str, float | int | bool]:
    """Extract canonical risk feature dictionary from TriageInput or dict.

    Handles both ``aarogya_clinical_engine.TriageInput`` objects and standard
    mapping/dict objects.
    """
    if hasattr(triage_input, "model_dump"):
        raw = triage_input.model_dump()
    elif isinstance(triage_input, dict):
        raw = triage_input
    else:
        raw = getattr(triage_input, "__dict__", {})

    danger_signs = raw.get("danger_signs") or []
    has_danger_sign = (
        bool(danger_signs)
        if isinstance(danger_signs, (list, set, tuple))
        else bool(raw.get("has_danger_sign", False))
    )

    symptoms = raw.get("symptoms") or []
    symptom_count = (
        len(symptoms)
        if isinstance(symptoms, (list, set, tuple))
        else int(raw.get("symptom_count", 0))
    )

    raw_features: dict[str, Any] = {
        "age_months": raw.get("age_months"),
        "fever_days": raw.get("fever_days", 0),
        "temperature_c": raw.get("temperature_c"),
        "respiratory_rate_bpm": raw.get("respiratory_rate_bpm"),
        "spo2_pct": raw.get("spo2_pct"),
        "systolic_bp": raw.get("systolic_bp"),
        "diastolic_bp": raw.get("diastolic_bp"),
        "hemoglobin_g_dl": raw.get("hemoglobin_g_dl"),
        "muac_cm": raw.get("muac_cm"),
        "is_pregnant": bool(raw.get("is_pregnant", False)),
        "gestational_weeks": raw.get("gestational_weeks"),
        "has_danger_sign": has_danger_sign,
        "symptom_count": symptom_count,
    }
    return {
        k: v
        for k, v in raw_features.items()
        if isinstance(v, (bool, int, float)) and not (isinstance(v, float) and math.isnan(v))
    }


def _safe_float(value: Any) -> float | None:
    if value is None or isinstance(value, bool):
        return None
    try:
        num = float(value)
    except (ValueError, TypeError):
        return None
    return None if math.isnan(num) or math.isinf(num) else num


def _age_rr_threshold(age_months: float | None) -> float:
    """Return WHO IMNCI / clinical fast-breathing threshold (breaths/min) by age band."""
    if age_months is None:
        return 35.0
    if age_months < 2.0:
        return 60.0
    if age_months < 12.0:
        return 50.0
    if age_months < 60.0:
        return 40.0
    return 24.0


def _calibrate_stub_fallback_features(
    features: dict[str, float | int | bool],
) -> dict[str, float | int | bool]:
    """Project canonical clinical vitals into bounded deficit/interaction features for StubRiskScorer.

    Captures age-band tachypnea thresholds, young-infant thermal instability,
    cardiorespiratory hypoxia+tachypnea synergy, gestational pre-eclampsia risk,
    severe anemia (<7 g/dL), and pediatric SAM (MUAC <11.5 cm) while preventing
    raw normal vital magnitudes from saturating the linear fallback at 1.0.
    """
    calibrated: dict[str, float | int | bool] = {}

    fever_days = _safe_float(features.get("fever_days"))
    if fever_days is not None:
        calibrated["fever_days"] = max(0.0, fever_days)

    if "has_danger_sign" in features:
        calibrated["has_danger_sign"] = bool(features["has_danger_sign"])

    symptom_count = _safe_float(features.get("symptom_count"))
    if symptom_count is not None:
        calibrated["symptom_count"] = max(0.0, symptom_count)

    age_months = _safe_float(features.get("age_months"))
    is_young_infant = False
    if "age_under_2m" in features:
        is_young_infant = bool(features["age_under_2m"])
        calibrated["age_under_2m"] = is_young_infant
    elif age_months is not None:
        is_young_infant = age_months < 2.0
        calibrated["age_under_2m"] = is_young_infant

    systolic_bp = _safe_float(features.get("systolic_bp"))
    diastolic_bp = _safe_float(features.get("diastolic_bp"))
    high_bp = False
    if "high_bp" in features:
        high_bp = bool(features["high_bp"])
        calibrated["high_bp"] = high_bp
    elif systolic_bp is not None or diastolic_bp is not None:
        high_bp = (systolic_bp is not None and systolic_bp >= 140.0) or (
            diastolic_bp is not None and diastolic_bp >= 90.0
        )
        calibrated["high_bp"] = high_bp

    is_pregnant = bool(features.get("is_pregnant", False))
    gestational_weeks = _safe_float(features.get("gestational_weeks"))
    if is_pregnant and high_bp and (gestational_weeks is None or gestational_weeks >= 20.0):
        calibrated["gestational_preeclampsia_risk"] = True

    temperature_c = _safe_float(features.get("temperature_c"))
    if temperature_c is not None:
        calibrated["temp_excess"] = round(max(0.0, temperature_c - 37.5), 4)
        if temperature_c < 35.5:
            calibrated["hypothermia_deficit"] = round(35.5 - temperature_c, 4)
        if is_young_infant and (temperature_c >= 37.5 or temperature_c < 35.5):
            calibrated["young_infant_thermal_risk"] = True

    spo2_pct = _safe_float(features.get("spo2_pct"))
    if spo2_pct is not None:
        calibrated["hypoxia_deficit"] = round(max(0.0, 95.0 - spo2_pct), 4)

    rr_threshold = _age_rr_threshold(age_months)
    rr_bpm = _safe_float(features.get("respiratory_rate_bpm"))
    tachypnea_excess = 0.0
    if rr_bpm is not None:
        tachypnea_excess = round(max(0.0, rr_bpm - rr_threshold), 4)
        calibrated["tachypnea_excess"] = tachypnea_excess
    elif "respiratory_rate" in features:
        rr_alt = _safe_float(features.get("respiratory_rate"))
        if rr_alt is not None:
            tachypnea_excess = round(max(0.0, rr_alt - rr_threshold), 4)
            calibrated["tachypnea_excess"] = tachypnea_excess

    if spo2_pct is not None and spo2_pct < 92.0 and tachypnea_excess > 0.0:
        calibrated["cardiorespiratory_distress"] = True

    hb = _safe_float(features.get("hemoglobin_g_dl"))
    if hb is not None:
        calibrated["anemia_deficit"] = round(max(0.0, 11.0 - hb), 4)
        if hb < 7.0:
            calibrated["severe_anemia_flag"] = True

    muac = _safe_float(features.get("muac_cm"))
    if muac is not None and (age_months is None or age_months < 60.0):
        calibrated["malnutrition_deficit"] = round(max(0.0, 12.5 - muac), 4)
        if muac < 11.5:
            calibrated["sam_malnutrition_flag"] = True

    return calibrated


class LightGbmRiskScorer:
    """Tabular risk scorer backed by LightGBM and exact TreeSHAP attribution.

    Gracefully falls back to ``StubRiskScorer`` if LightGBM is not installed or
    the serialized model file is missing, setting ``backend='stub-lightgbm-fallback'``.
    """

    def __init__(
        self,
        model_path: str | Path | None = None,
        *,
        fallback_scorer: RiskScorer | None = None,
        portable_artifact_path: str | Path | None = None,
    ) -> None:
        self._model_path = Path(model_path) if model_path is not None else _default_model_path()
        self._custom_fallback = fallback_scorer is not None
        self._fallback_scorer = fallback_scorer or StubRiskScorer()
        self._is_fallback = False
        self._booster: Any = None
        self._portable_model: PortableGbdtModel | None = None

        artifact_path = (
            Path(portable_artifact_path)
            if portable_artifact_path is not None
            else DEFAULT_ARTIFACT_PATH
        )
        if artifact_path.is_file():
            try:
                self._portable_model = PortableGbdtModel.from_json_file(artifact_path)
            except Exception:
                self._portable_model = None

        if lgb is None or np is None:
            self._is_fallback = True
            return

        if not self._model_path.is_file():
            self._is_fallback = True
            return

        try:
            self._booster = lgb.Booster(model_file=str(self._model_path))
        except Exception:
            self._is_fallback = True

    @property
    def is_fallback(self) -> bool:
        """Whether the scorer is operating in offline fallback mode."""
        return self._is_fallback

    @property
    def model_path(self) -> Path:
        """The resolved path to the LightGBM model file."""
        return self._model_path

    @property
    def portable_model(self) -> PortableGbdtModel | None:
        """The embedded pure-Python GBDT + exact TreeSHAP model, if loaded."""
        return self._portable_model

    def _build_feature_row(
        self,
        features: dict[str, float | int | bool],
        *,
        use_neutral_defaults: bool = False,
    ) -> list[float]:
        """Build canonical RISK_FEATURE_NAMES float vector.

        When ``use_neutral_defaults=True`` (used by the embedded portable GBDT+TreeSHAP
        evaluator), omitted numeric vitals/labs are imputed to clinically normal neutral
        baselines so unmeasured labs (e.g. omitted Hb/MUAC/SpO2) never masquerade as
        critical pathology.
        """
        is_pregnant = bool(features.get("is_pregnant", False))
        age_raw = _safe_float(features.get("age_months"))
        is_adult = is_pregnant or (age_raw is not None and age_raw >= 60.0)
        neutral_defaults: dict[str, float] = {
            "age_months": 288.0 if is_pregnant else 36.0,
            "fever_days": 0.0,
            "temperature_c": 37.0,
            "respiratory_rate_bpm": 20.0 if is_adult else 24.0,
            "spo2_pct": 98.0,
            "systolic_bp": 115.0,
            "diastolic_bp": 75.0,
            "hemoglobin_g_dl": 12.0,
            "muac_cm": 24.0 if is_adult else 14.5,
            "is_pregnant": 0.0,
            "gestational_weeks": float("nan"),
            "has_danger_sign": 0.0,
            "symptom_count": 0.0,
        }
        defaults = neutral_defaults if use_neutral_defaults else DEFAULT_FEATURE_VALUES

        row: list[float] = []
        for name in RISK_FEATURE_NAMES:
            if name in features and features[name] is not None:
                val = features[name]
                if isinstance(val, bool):
                    row.append(1.0 if val else 0.0)
                else:
                    try:
                        num = float(val)
                        row.append(defaults[name] if math.isnan(num) else num)
                    except (ValueError, TypeError):
                        row.append(defaults[name])
            elif name == "respiratory_rate_bpm" and features.get("respiratory_rate") is not None:
                val = features["respiratory_rate"]
                try:
                    num = float(val)
                    row.append(defaults[name] if math.isnan(num) else num)
                except (ValueError, TypeError):
                    row.append(defaults[name])
            else:
                row.append(defaults[name])
        return row

    @staticmethod
    def _band_for_score(risk_score: float) -> Literal["LOW", "MODERATE", "HIGH"]:
        if risk_score >= 0.70:
            return "HIGH"
        if risk_score >= 0.35:
            return "MODERATE"
        return "LOW"

    def _score_with_fallback(self, features: dict[str, float | int | bool]) -> RiskScoreResult:
        if not self._custom_fallback and self._portable_model is not None:
            row = self._build_feature_row(features, use_neutral_defaults=True)
            raw_prob, _margin, _base_val, attributions = self._portable_model.explain(row)
            risk_score = round(max(0.0, min(1.0, raw_prob)), 4)
            return RiskScoreResult(
                risk_score=risk_score,
                risk_band=self._band_for_score(risk_score),
                shap_attributions=attributions,
                backend="stub-lightgbm-fallback",
            )

        fallback_input = (
            _calibrate_stub_fallback_features(features)
            if isinstance(self._fallback_scorer, StubRiskScorer)
            else features
        )
        fallback_res = self._fallback_scorer.score_risk(fallback_input)
        return RiskScoreResult(
            risk_score=fallback_res.risk_score,
            risk_band=fallback_res.risk_band,
            shap_attributions=fallback_res.shap_attributions,
            backend="stub-lightgbm-fallback",
        )

    def score_risk(self, features: dict[str, float | int | bool]) -> RiskScoreResult:
        """Compute calibrated risk score, risk band, and TreeSHAP attributions."""
        if self._is_fallback or self._booster is None or np is None:
            return self._score_with_fallback(features)

        row = self._build_feature_row(features)
        x_vec = np.array([row], dtype=np.float64)

        try:
            raw_prob = float(self._booster.predict(x_vec)[0])
        except Exception:
            return self._score_with_fallback(features)

        risk_score = round(max(0.0, min(1.0, raw_prob)), 4)
        risk_band = self._band_for_score(risk_score)

        # Compute per-feature exact TreeSHAP attributions using pred_contrib=True
        attributions: dict[str, float] = {}
        try:
            contribs = self._booster.predict(x_vec, pred_contrib=True)[0]
            for idx, feat_name in enumerate(RISK_FEATURE_NAMES):
                val = float(contribs[idx])
                attributions[feat_name] = 0.0 if math.isnan(val) else round(val, 4)
        except Exception:
            # Fallback attributions if contrib extraction fails
            for feat_name in RISK_FEATURE_NAMES:
                attributions[feat_name] = 0.0

        return RiskScoreResult(
            risk_score=risk_score,
            risk_band=risk_band,
            shap_attributions=attributions,
            backend="lightgbm-treeshap",
        )
