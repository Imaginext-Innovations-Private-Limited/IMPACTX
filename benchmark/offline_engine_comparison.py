def cases(table):
    return [(lang, text, label) for lang, pairs in table.items()
            for suspicious, benign in pairs for text, label in [(suspicious, 1), (benign, 0)]]


def evaluate(name, sets):
    rows = []
    for dataset, table in sets:
        for lang, text, label in cases(table):
            result = engine.analyze(text, language='en')
            rows.append(dict(model=name, dataset=dataset, language=lang, text=text,
                             expected_suspicious=label, level=result['level'],
                             flagged=int(result['level'] in {'review', 'caution', 'high'})))
    return rows


